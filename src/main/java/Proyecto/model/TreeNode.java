package Proyecto.model;

/**
 * Representa un nodo de un árbol binario.
 */
public class TreeNode {
    public int val;
    public TreeNode left;
    public TreeNode right;

    /**
     * Constructor del nodo.
     *
     * @param val valor del nodo
     */
    public TreeNode(int val) {
        this.val = val;
    }
}
